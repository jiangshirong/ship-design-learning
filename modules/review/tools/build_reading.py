def linear(tex):
    value=re.sub(r'\\mathrm\{([^{}]*)\}',r'\1',tex)
    value=re.sub(r'_\{([^{}]*)\}',r'_\1',value)
    value=re.sub(r'\\frac\{([^{}]*)\}\{([^{}]*)\}',r'(\1)/(\2)',value)
    return value.replace(r'\,',' ').replace(r'\times',' × ').replace(r'\approx',' ≈ ')
