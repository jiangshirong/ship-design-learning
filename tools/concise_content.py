def simplify(courses):
    for c in courses:
        if c['id']=='sample':
            c['initial']['cargo_detail']=True
            c['title']={'zh':'移动货物与重心','ru':'Перемеще́ние гру́за и центр тя́жести'}
            c['goal']={'zh':'100 吨货物降低 6 米，求全船 G 的位移。','ru':'Груз 100 т опуска́ется на 6 м. Найти́ смеще́ние G су́дна.'}
        aliases=c.setdefault('resume_aliases',{})
        for g in c['groups']:
            kept=[]
            for b in g['beats']:
                if b.get('is_note'):
                    kept[-1]['details'].append(b['words']);aliases[b['id']]=kept[-1]['id'];continue
                b['details']=[b['words']]
                if b['id'] in TEXT:
                    zh,ru=TEXT[b['id']];b['words']={'zh':zh,'ru':ru}
                if b['id'].startswith('load-fuel:') and b['id'].split(':')[-1].isdigit():
                    n=int(b['id'].split(':')[-1])+1
                    b['words']={'zh':f'燃油舱 {n}：质量乘坐标，得到质量矩。','ru':f'Цисте́рна {n}: ма́сса × координа́та = моме́нт.'}
                if b['id'].startswith('load-ship:'):
                    name=b['words']['zh'].split('：')[0]
                    b['words']['zh']=name+'：计算质量矩并累加。'
                    b['words']['ru']=b['words']['ru'].split(':')[0]+': счита́ем и складыва́ем моме́нты.'
                if b['id'] in ['sample:known','sample:move']:
                    b['details']=[b['words'],{'zh':'钢卷仅为货物外观示意；原题未给出货物种类和尺寸。模型原点使用题目重心坐标，质量仍为 100 t。','ru':'Руло́ны — усло́вный вид гру́за: тип и размере́ры в зада́нии не да́ны. Нача́ло мо́дели совпа́дает с за́данным це́нтром гру́за; ма́сса — 100 т.'}]
                b['text']=b['words']['zh'];kept.append(b)
            g['beats']=kept
    return courses
